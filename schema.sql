-- Selby Premier League - Supabase starter schema
-- Run this in Supabase SQL Editor before connecting the site.

create extension if not exists pgcrypto;

create table if not exists public.players (
  id uuid primary key default gen_random_uuid(),
  name text not null unique,
  sort_order int not null
);

create table if not exists public.rounds (
  id bigint generated by default as identity primary key,
  round_number int not null unique check (round_number between 1 and 9),
  play_date date null,
  host text null
);

create table if not exists public.fixtures (
  id bigint generated by default as identity primary key,
  round_number int not null references public.rounds(round_number) on delete cascade,
  player1 text not null references public.players(name),
  player2 text not null references public.players(name),
  player1_legs int null check (player1_legs between 0 and 5),
  player2_legs int null check (player2_legs between 0 and 5),
  player1_average numeric(5,2) null check (player1_average between 0 and 180),
  player2_average numeric(5,2) null check (player2_average between 0 and 180),
  unique(player1, player2),
  check (player1 <> player2)
);

create table if not exists public.league_settings (
  id int primary key default 1 check (id = 1),
  fixtures_locked boolean not null default false
);

create table if not exists public.admin_users (
  user_id uuid primary key references auth.users(id) on delete cascade
);

