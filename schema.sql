create policy "public read players" on public.players for select using (true);
create policy "public read rounds" on public.rounds for select using (true);
create policy "public read fixtures" on public.fixtures for select using (true);
create policy "public read settings" on public.league_settings for select using (true);

create or replace function public.is_spl_admin()
returns boolean
language sql stable security definer
set search_path = public
as $$
  select exists(select 1 from public.admin_users where user_id = auth.uid());
$$;

create policy "admins manage rounds" on public.rounds
for all using (public.is_spl_admin()) with check (public.is_spl_admin());

create policy "admins manage fixtures" on public.fixtures
for all using (public.is_spl_admin()) with check (public.is_spl_admin());

create policy "admins manage settings" on public.league_settings
for all using (public.is_spl_admin()) with check (public.is_spl_admin());

